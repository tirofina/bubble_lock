import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { Ajv2020 } from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';

const directory = new URL('../', import.meta.url);
const schema = JSON.parse(await readFile(new URL('contracts/dashboard-event.schema.json', directory), 'utf8'));
const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true } });
addFormats(ajv);
ajv.addSchema(schema);
const source = standaloneCode(ajv, {
  eventValidator: schema.$id,
  receiptValidator: `${schema.$id}#/$defs/coreReceipt`,
  integrationValidator: `${schema.$id}#/$defs/integrationReceipt`,
});
// Bundle Ajv's CommonJS format/runtime helpers into static browser ESM.
const result = await build({
  absWorkingDir: fileURLToPath(directory),
  stdin: { contents: source, resolveDir: fileURLToPath(directory), sourcefile: 'validators.ajv.js' },
  bundle: true,
  platform: 'browser',
  format: 'esm',
  target: 'es2023',
  minify: true,
  legalComments: 'none',
  write: false,
});
const banner = '// Generated by scripts/build-validators.mjs. Do not edit.\n';
const artifacts = {
  'validators.generated.mjs': banner + result.outputFiles[0].text,
  'validators.generated.d.mts': banner + `import type { ValidateFunction } from 'ajv';
import type { CoreReceipt, DashboardEvent, IntegrationReceipt } from './types.ts';
export declare const eventValidator: ValidateFunction<DashboardEvent>;
export declare const receiptValidator: ValidateFunction<CoreReceipt>;
export declare const integrationValidator: ValidateFunction<IntegrationReceipt>;
`,
};
for (const [name, content] of Object.entries(artifacts)) {
  const destination = new URL(`shared/${name}`, directory);
  if (process.argv.includes('--check')) {
    if (await readFile(destination, 'utf8') !== content) {
      throw new Error(`${name} is stale; run npm run build:validators`);
    }
  } else {
    await writeFile(destination, content);
  }
}
console.log(process.argv.includes('--check') ? 'Generated validators are current' : 'Generated browser validators');
