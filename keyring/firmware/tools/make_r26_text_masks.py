"""Generate the r26 LCD's native-resolution text masks from Barlow Semi Condensed."""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


LABELS = (
    ("Ready", "READY", "SemiBold", 38),
    ("Confirm", "CONFIRM", "SemiBold", 38),
    ("Panic", "PANIC", "SemiBold", 38),
    ("ReadyHint", "Press a button", "Medium", 20),
    ("ConfirmHint", "Input received", "Medium", 20),
    ("PanicHint", "Emergency input", "Medium", 20),
    ("Battery", "Battery", "SemiBold", 19),
)


def render_mask(font_dir: Path, text: str, weight: str, size: int) -> tuple[Image.Image, bytes]:
    scale = 4
    font_path = font_dir / f"BarlowSemiCondensed-{weight}.ttf"
    font = ImageFont.truetype(str(font_path), size * scale)
    left, top, right, bottom = font.getbbox(text)
    padding = 2 * scale
    width = (right - left + 2 * padding + scale - 1) // scale
    height = (bottom - top + 2 * padding + scale - 1) // scale
    mask = Image.new("L", (width * scale, height * scale))
    ImageDraw.Draw(mask).text((padding - left, padding - top), text, font=font, fill=255)
    mask = mask.resize((width, height), Image.Resampling.LANCZOS)
    mask = mask.point([min(15, (value + 8) // 17) for value in range(256)])
    mask = mask.crop(mask.getbbox())
    samples = mask.tobytes()
    if len(samples) % 2:
        samples += b"\0"
    return mask, bytes((one << 4) | two for one, two in zip(samples[::2], samples[1::2]))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font_dir", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    blocks = ["""// Generated by tools/make_r26_text_masks.py. Do not edit.
// Artwork rasterized from Barlow Semi Condensed by the Barlow Project Authors (OFL 1.1).
#pragma once
#include <stdint.h>

namespace r26text {
struct Mask {
  int16_t width, height;
  const uint8_t *alpha;
};
"""]
    for name, text, weight, size in LABELS:
        mask, packed = render_mask(args.font_dir, text, weight, size)
        rows = [", ".join(f"0x{value:02x}" for value in packed[i:i + 16])
                for i in range(0, len(packed), 16)]
        blocks.append(f"constexpr uint8_t {name}Alpha[] = {{\n  " + ",\n  ".join(rows) + "\n};")
        blocks.append(f"constexpr Mask {name}{{{mask.width}, {mask.height}, {name}Alpha}};\n")
    blocks.append("}\n")
    args.output.write_text("\n".join(blocks), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
