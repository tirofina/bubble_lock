"""Build the r26 header bitmap from the provided Privacy Bubble logo PNG."""

import argparse
from pathlib import Path

from PIL import Image


def rgb565(red: int, green: int, blue: int) -> int:
    return ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)


def crop_art(source: Image.Image, bounds: tuple[int, int, int, int]) -> Image.Image:
    art = source.crop(bounds)
    opaque_bounds = art.getchannel("A").point(lambda alpha: 255 if alpha >= 128 else 0).getbbox()
    if opaque_bounds is None:
        raise ValueError("The logo region contains no opaque artwork")
    return art.crop(opaque_bounds)


def for_dark_background(art: Image.Image) -> Image.Image:
    themed = art.copy()
    themed.putdata([
        (80, 207, 182, alpha) if green > 90 and green - red > 45 else (235, 246, 247, alpha)
        for red, green, _, alpha in art.get_flattened_data()
    ])
    return themed


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()

    with Image.open(args.source) as image:
        source = image.convert("RGBA")
    if source.size != (2172, 724):
        raise ValueError("Expected the supplied 2172×724 Privacy Bubble Keyring logo")
    symbol = for_dark_background(crop_art(source, (0, 0, 575, source.height)))
    wordmark = for_dark_background(crop_art(source, (580, 0, source.width, 421)))
    symbol.thumbnail((32, 34), Image.Resampling.LANCZOS)
    wordmark.thumbnail((142, 28), Image.Resampling.LANCZOS)
    background = (12, 20, 27)
    logo = Image.new("RGBA", (symbol.width + 10 + wordmark.width, 34), background + (255,))
    logo.alpha_composite(symbol, (0, (logo.height - symbol.height) // 2))
    logo.alpha_composite(wordmark, (symbol.width + 10, (logo.height - wordmark.height) // 2))

    pixels = [rgb565(*color) for color in logo.convert("RGB").get_flattened_data()]
    lines = [", ".join(f"0x{value:04x}" for value in pixels[i:i + 12])
             for i in range(0, len(pixels), 12)]
    header = f"""// Generated by tools/make_r26_logo.py. Source: team-provided Privacy Bubble logo.
#pragma once
#include <stdint.h>

namespace r26logo {{
constexpr uint16_t Background = 0x{rgb565(*background):04x};
constexpr int16_t Width = {logo.width};
constexpr int16_t Height = {logo.height};
constexpr uint16_t Pixels[] = {{
  """ + ",\n  ".join(lines) + "\n};\n}\n"
    args.output.write_text(header, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
