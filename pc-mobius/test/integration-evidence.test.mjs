import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { buildIntegrationEvidence, sourceCollection } from '../scripts/build-integration-evidence.mjs';

test('통합 소스 manifest는 결정적 해시와 공개 입력 경계를 보존한다', async (t) => {
  const temporary = await mkdtemp(join(tmpdir(), 'bubble-source-manifest-'));
  t.after(() => rm(temporary, { recursive: true, force: true }));
  const basePath = join(temporary, 'pc-mobius');
  for (const rule of sourceCollection) await mkdir(join(basePath, rule.directory), { recursive: true });
  const write = async (path, value) => { const absolute = join(basePath, path); await mkdir(dirname(absolute), { recursive: true }); await writeFile(absolute, value); };
  await write('package.json', '{}'); await write('package-lock.json', '{}');
  await write('integration/src/z.mjs', 'export const z = 1;');
  await write('integration/src/nested/a.mjs', 'export const a = 1;');
  await write('contracts/new.schema.json', '{}');
  await write('../contracts/keyring/observation.schema.json', '{}');
  await write('config/integration-api.example.json', '{}');
  await write('config/mobius.env.example', 'CSE_URL=https://example.test');
  await write('db/migrations/003_runtime.sql', 'SELECT 1;');
  await write('scripts/run-new.mjs', 'export {};');
  await write('test/new.test.mjs', 'export {};');
  const excluded = ['.local/production.json', 'config/production.json', 'config/private.pem', 'integration/src/.local/private.mjs', 'integration/release/manifest.json', 'receipts/success.json', 'config/.env'];
  for (const path of excluded) await write(path, 'private fixture');
  const first = await buildIntegrationEvidence({ basePath, generatedAt: '2026-11-10T00:00:00.000Z' });
  const second = await buildIntegrationEvidence({ basePath, generatedAt: first.generatedAt });
  assert.deepEqual(second, first);
  assert.equal(first.artifacts.length, 11);
  const paths = first.artifacts.map((artifact) => artifact.path);
  assert.deepEqual(paths, [...paths].sort());
  for (const path of excluded) assert.equal(paths.includes(path), false);
  assert.equal(first.sourceDigest, createHash('sha256').update(JSON.stringify(first.artifacts)).digest('hex'));
  assert.deepEqual(first.evidence.receipts, []);
  assert.equal(first.evidence.kind, 'SOURCE_INTEGRITY');
  assert.equal(first.evidence.verification, 'SEPARATE_EXECUTION_RECEIPTS');
  await write('integration/src/z.mjs', 'export const z = 2;');
  const changed = await buildIntegrationEvidence({ basePath });
  assert.notEqual(changed.sourceDigest, first.sourceDigest);
  assert.equal(changed.artifacts.find((artifact) => artifact.path === 'integration/src/z.mjs').bytes, 19);
});
